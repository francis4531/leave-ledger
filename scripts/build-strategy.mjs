// Runs on every Netlify build. Bundles strategy/*.md into the API so the
// /strategy page can show them to signed-in test users only.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "strategy");
const files = {};
function walk(d) {
  if (!fs.existsSync(d)) return;
  for (const name of fs.readdirSync(d).sort()) {
    const p = path.join(d, name);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".md")) files[path.relative(dir, p).split(path.sep).join("/")] = fs.readFileSync(p, "utf8");
  }
}
walk(dir);
const out = path.join(root, "netlify", "lib", "strategy-data.mjs");
fs.writeFileSync(out, `// Generated by scripts/build-strategy.mjs on each build. Do not edit.\nexport default ${JSON.stringify({ builtAt: new Date().toISOString(), files }, null, 0)};\n`);
console.log(`strategy: bundled ${Object.keys(files).length} files`);

// Build label shown at the bottom of every page: commit count and short commit id, from Netlify's build settings or git.
import { execSync } from "node:child_process";
const git = (c) => { try { return execSync(c, { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { return ""; } };
const commit = (process.env.COMMIT_REF || git("git rev-parse HEAD")).slice(0, 7);
const shallow = git("git rev-parse --is-shallow-repository") === "true";
const count = shallow ? "" : git("git rev-list --count HEAD");
const build = { number: count ? +count : null, commit: commit || null, builtAt: new Date().toISOString(), context: process.env.CONTEXT || "local" };
fs.writeFileSync(path.join(root, "public", "build.json"), JSON.stringify(build));
console.log(`build: ${build.number ?? "?"} (${build.commit})`);
