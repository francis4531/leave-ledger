// Runs the unit tests (as the deploy gate) and saves the results for the admin /tests page.
// Writes netlify/lib/test-results.mjs (generated, not committed). Exits non-zero if any test fails, so the deploy stops.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const tmp = path.join(root, ".netlify", "test-events.json");
fs.mkdirSync(path.dirname(tmp), { recursive: true });
const started = Date.now();
const r = spawnSync(process.execPath, ["--test", "--test-reporter=spec", "--test-reporter-destination=stdout",
  `--test-reporter=${path.join(root, "scripts", "test-json-reporter.mjs")}`, `--test-reporter-destination=${tmp}`, "tests/*.test.mjs"],
  { cwd: root, stdio: ["ignore", "inherit", "inherit"] });

// Which part of the product each test file covers, in plain words.
const AREAS = {
  "rules.test.mjs": "Leave rules (answer key)", "local-sick.test.mjs": "City sick leave", "access.test.mjs": "Access, privacy and security",
  "notices.test.mjs": "Letters and notices", "roster.test.mjs": "Employee import and manager notice", "guide.test.mjs": "Guide and state pay steps",
};
let events = [];
try { events = JSON.parse(fs.readFileSync(tmp, "utf8")); } catch (e) { events = []; }
// Keep the tests themselves (leaves), and name each by the group it sits in.
const tests = [], pending = [];
events.forEach((ev, i) => {
  const prev = events[i - 1], parent = ev.type === "suite" || (prev && prev.nesting > ev.nesting && prev.file === ev.file);
  if (parent) { for (const t of pending) if (t.nesting > ev.nesting && !t.group) t.group = ev.name; return; }
  const t = { area: AREAS[path.basename(ev.file || "")] || path.basename(ev.file || "other"), name: ev.name, ok: ev.ok, skip: ev.skip, ms: ev.ms, error: ev.ok ? null : ev.error, nesting: ev.nesting };
  tests.push(t); pending.push(t);
});
let build = null; try { build = JSON.parse(fs.readFileSync(path.join(root, "public", "build.json"), "utf8")); } catch (e) {}
const out = {
  build: build ? build.number : null, sha: build ? build.commit : null, context: build ? build.context : "local", at: new Date().toISOString(), ms: Date.now() - started,
  passed: tests.filter((t) => t.ok && !t.skip).length, failed: tests.filter((t) => !t.ok).length, skipped: tests.filter((t) => t.skip).length,
  tests: tests.map(({ nesting, ...t }) => t),
};
fs.writeFileSync(path.join(root, "netlify", "lib", "test-results.mjs"), "// Generated by scripts/run-tests.mjs on each build. Do not edit.\nexport default " + JSON.stringify(out) + ";\n");
console.log(`tests: ${out.passed} passed, ${out.failed} failed, saved for /tests`);
process.exit(r.status === 0 && out.failed === 0 ? 0 : 1);
