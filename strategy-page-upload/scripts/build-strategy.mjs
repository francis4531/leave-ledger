// Runs on every Netlify build. Bundles strategy/*.md into the API so the
// /strategy page can show them to signed-in test users only.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "strategy");
const files = {};
function walk(d) {
  if (!fs.existsSync(d)) return;
  for (const name of fs.readdirSync(d).sort()) {
    const p = path.join(d, name);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".md")) files[path.relative(dir, p).split(path.sep).join("/")] = fs.readFileSync(p, "utf8");
  }
}
walk(dir);
const out = path.join(root, "netlify", "lib", "strategy-data.mjs");
fs.writeFileSync(out, `// Generated by scripts/build-strategy.mjs on each build. Do not edit.\nexport default ${JSON.stringify({ builtAt: new Date().toISOString(), files }, null, 0)};\n`);
console.log(`strategy: bundled ${Object.keys(files).length} files`);
